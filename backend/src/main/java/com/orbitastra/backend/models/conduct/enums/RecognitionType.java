package com.orbitastra.backend.models.new_new.conduct.enums;

/** What a child is being recognised for. */
public enum RecognitionType {
    /** Marks, a project or academic effort. */
    ACADEMIC,

    /** Sport, at school or outside it. */
    SPORTS,

    /** Music, art, dance, drama or writing. */
    ARTS,

    /** Leading, organising or representing others. */
    LEADERSHIP,

    /** Kindness, honesty or helping somebody. The one schools forget to record. */
    GOOD_CONDUCT,

    /** Getting noticeably better, whatever the starting point. */
    IMPROVEMENT,

    /** Being there, reliably. */
    ATTENDANCE,

    /** Something done outside school that reflects well on it. */
    COMMUNITY,

    /** Anything the types above do not cover. */
    OTHER
}
